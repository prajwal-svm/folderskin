/** True when there is a logo for provider `id`. */
export const hasProviderLogo = (id: string) => id in MONO || id === "google" || id === "stability";

/** The logo of AI provider `id` (the catalogue's ids), or nothing for one without a logo here. */
export function ProviderLogo({ id, size = 16, className }: { id: string; size?: number; className?: string }) {
  // Gradient ids have to be unique on the page, and a React id's punctuation isn't welcome in
  // `url(#…)`.
  const uid = useId().replace(/[^A-Za-z0-9_-]/g, "");
  const svg = { width: size, height: size, viewBox: "0 0 24 24", className, "aria-hidden": true, focusable: false } as const;

  if (id === "google") {
    return (
      <svg {...svg}>
        <path d={GEMINI} fill="#3186FF" />
        <path d={GEMINI} fill={`url(#${uid}g0)`} />
        <path d={GEMINI} fill={`url(#${uid}g1)`} />
        <path d={GEMINI} fill={`url(#${uid}g2)`} />
        <defs>
          <linearGradient gradientUnits="userSpaceOnUse" id={`${uid}g0`} x1="7" x2="11" y1="15.5" y2="12">
            <stop stopColor="#08B962" />
            <stop offset="1" stopColor="#08B962" stopOpacity="0" />
          </linearGradient>
          <linearGradient gradientUnits="userSpaceOnUse" id={`${uid}g1`} x1="8" x2="11.5" y1="5.5" y2="11">
            <stop stopColor="#F94543" />
            <stop offset="1" stopColor="#F94543" stopOpacity="0" />
          </linearGradient>
          <linearGradient gradientUnits="userSpaceOnUse" id={`${uid}g2`} x1="3.5" x2="17.5" y1="13.5" y2="12">
            <stop stopColor="#FABC12" />
            <stop offset=".46" stopColor="#FABC12" stopOpacity="0" />
          </linearGradient>
        </defs>
      </svg>
    );
  }
  if (id === "stability") {
    return (
      <svg {...svg}>
        <path d={STABILITY_S} fill={`url(#${uid}s)`} />
        <path d={STABILITY_DOT} fill="#E80000" />
        <defs>
          <linearGradient id={`${uid}s`} x1="50%" x2="50%" y1="0%" y2="100%">
            <stop offset="0%" stopColor="#9D39FF" />
            <stop offset="100%" stopColor="#A380FF" />
          </linearGradient>
        </defs>
      </svg>
    );
  }
  const paths = MONO[id];
  if (!paths) return null;
  return (
    <svg {...svg} fill="currentColor" fillRule="evenodd">
      {paths.map((d) => (
        <path key={d} d={d} />
      ))}
    </svg>
  );
}
